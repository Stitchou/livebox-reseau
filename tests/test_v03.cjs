const fs=require('fs'),vm=require('vm'),assert=require('node:assert/strict');
const source=fs.readFileSync(__dirname+'/www/livebox-reseau-card.js','utf8');
const window={customCards:[]};const registry=new Map();
const context={window,customElements:{get:k=>registry.get(k),define:(k,v)=>registry.set(k,v)},HTMLElement:class{},console,setTimeout,clearTimeout,localStorage:{getItem:()=>null},matchMedia:()=>({matches:true})};
vm.createContext(context);vm.runInContext(source,context);
let n=0;const check=(a,b,msg)=>{assert.equal(a,b,msg);n++;};
const state=(name,ifname,ip,connection='ethernet',online=true)=>({entity_id:'device_tracker.'+name.toLowerCase().replace(/ /g,'_'),state:online?'home':'not_home',attributes:{friendly_name:name,source_type:'router',ip,mac:'AC:00:00:00:00:'+ip.split('.').pop().padStart(2,'0'),interface_name:ifname,connection}});
const entries=[state('Velop RDC','ETH2','192.168.1.12'),state('Alexa salon','ETH2','192.168.1.36'),state('Barre de son','ETH2','192.168.1.20'),state('HA','ETH1','192.168.1.64'),state('Wifi Phone','wl0','192.168.1.50','wifi',false),{entity_id:'device_tracker.gps',state:'home',attributes:{source_type:'gps',friendly_name:'GPS'}}];
const devices=vm.runInContext('liveboxReadDevices',context)({states:Object.fromEntries(entries.map(x=>[x.entity_id,x]))});
check(devices.length,5,'exclusion GPS');
check(devices.find(x=>x.name==='HA').groupKey,'eth:ETH1');
check(devices.find(x=>x.name==='Wifi Phone').type,'wifi');
const treeFn=vm.runInContext('liveboxTree',context);
let tree=treeFn(devices,{},true),eth2=tree.find(x=>x.key==='eth:ETH2');
check(eth2.roots.length,1,'Velop regroupement');check(eth2.roots[0].name,'Velop RDC');check(eth2.roots[0].children.length,2);
check(eth2.roots[0].children[0].link,'wifi');
let override={'mac:AC:00:00:00:00:36':{name:'Alexa bureau',parent:'interface'}};
// use real device key even when MAC differs from these fixture assumptions
const alexa=devices.find(x=>x.name==='Alexa salon');override={['mac:'+alexa.mac]:{name:'Alexa modifiée',parent:'interface'}};
tree=treeFn(devices,override,true);eth2=tree.find(x=>x.key==='eth:ETH2');
check(eth2.roots.length,2,'parent cassé à la demande');check(eth2.roots.some(x=>x.name==='Alexa modifiée'),true);
const ha=devices.find(x=>x.name==='HA'),velop=devices.find(x=>x.name==='Velop RDC');
const loops={['mac:'+ha.mac]:{parent:velop.entityId},['mac:'+velop.mac]:{parent:ha.entityId}};
tree=treeFn(devices,loops,false);const roots=tree.flatMap(g=>g.roots);
check(roots.length>=3,true,'rupture de cycle');
const prune=vm.runInContext('liveboxPrune',context);
tree=treeFn(devices,{},true);eth2=tree.find(x=>x.key==='eth:ETH2');
check(prune(eth2.roots[0],'alexa',false).children.length,1,'recherche dans descendants');
check(prune(eth2.roots[0],'aucun',false),null,'recherche absente');
const exportYaml=vm.runInContext('liveboxExport',context);
check(exportYaml({title:'Réseau',grid_options:{columns:'full',rows:'auto'}},{}).includes('columns: full'),true);
check(registry.has('livebox-reseau-card'),true,'custom element');
check(source.includes("this._backendStatus==='ready'"),true,'store status');
check(source.includes('livebox_reseau/set'),true,'backend save');
check(source.includes('(max-width:620px)'),true,'responsive');
console.log('LOGIC_TESTS_OK: '+n+' assertions');
